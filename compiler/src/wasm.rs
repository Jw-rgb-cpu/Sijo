//! `sijoc build --target wasm32`: the JS loader and the web page that go next to the .wasm.
//!
//! The C code is the embedding library (`--lib`) with its own C library (runtime/sijo_wasm.h). The
//! loader instantiates the module, gives it what that C library imports (console output, a clock,
//! files kept in memory, the panic unwinder) and the game's host functions (`extern` in Sijo, taken
//! from the `host` object with strings as JS strings and arrays as typed arrays), and wraps the API:
//! a panic in game code comes back as a JS exception, which the wrappers turn into the API's error
//! result (`step()` returns 0 and `error()` the message), as the native library does.

use crate::driver::Compiled;
use std::fmt::Write;

/// JS typed array for a C element type
fn typed(el: &str) -> &'static str {
    match el {
        "float" => "Float32Array",
        "bool" => "Uint8Array",
        _ => "Int32Array",
    }
}

/// the loader module (`<stem>.js`)
pub fn loader(c: &Compiled, prefix: &str, stem: &str) -> String {
    let g = crate::codegen::wasm_meta(c, prefix);
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// {stem}.js - generated by sijoc {ver} (sijoc build --target wasm32): loads {stem}.wasm and wraps the
// embedding API of sijo_game.h for JavaScript. Do not edit: rebuild instead.
//
//   import {{ load }} from \"./{stem}.js\";
//   const game = await load({{ /* host functions (extern in Sijo) by C name */ }});
//   game.create(42n); game.step(); game.draws(); game.error(); game.checksum();
//
// A panic in game code stops the game, as in the native library: step() returns 0 and error() has
// the message (with the .sijo file and line); load() of a saved state makes it run again.",
        ver = env!("CARGO_PKG_VERSION")
    );
    o.push_str(
        r#"const UNWIND = Symbol("sijo panic");
export class SijoExit extends Error {
  constructor(code) { super(`the game called exit(${code})`); this.code = code; }
}

/** host: { <C name of an extern>: function, print(fd, line), files: Map<string, Uint8Array> }
 *  wasm: URL, path or bytes of the module (default: next to this file) */
export async function load(host = {}, wasm = new URL("./STEM.wasm", import.meta.url)) {
  const files = host.files ?? new Map();
  const print = host.print ?? ((fd, line) => (fd === 2 ? console.error : console.log)(line));
  const dec = new TextDecoder(), enc = new TextEncoder();
  let mem = null, x = null;
  const u8 = () => new Uint8Array(mem.buffer);
  const str = (p, n) => dec.decode(u8().subarray(p, p + n));
  const cstrAt = (p) => { const b = u8(); let e = p; while (b[e]) e++; return dec.decode(b.subarray(p, e)); };
  const pending = { 1: "", 2: "" };
  const missing = new Set();
  const call = (name, args) => {
    const f = host[name];
    if (typeof f === "function") return f(...args);
    if (!missing.has(name)) { missing.add(name); console.warn(`sijo: host function ${name} is not provided (it does nothing)`); }
    return 0;
  };
  const env = {
    sijo_wasm_write(fd, p, n) {
      pending[fd] = (pending[fd] ?? "") + str(p, n);
      let i;
      while ((i = pending[fd].indexOf("\n")) >= 0) { print(fd, pending[fd].slice(0, i)); pending[fd] = pending[fd].slice(i + 1); }
    },
    sijo_wasm_now() { return performance.now() / 1000; },
    sijo_wasm_unwind() { throw UNWIND; },
    sijo_wasm_exit(code) { throw new SijoExit(code); },
    sijo_wasm_file_size(p, n) { const f = files.get(str(p, n)); return f ? f.length : -1; },
    sijo_wasm_file_read(p, n, dst) { u8().set(files.get(str(p, n)), dst); },
    sijo_wasm_file_write(p, n, src, len) { files.set(str(p, n), u8().slice(src, src + len)); },
    sijo_wasm_file_remove(p, n) { return files.delete(str(p, n)) ? 0 : -1; },
"#
        .replace("STEM", stem)
        .as_str(),
    );
    // host functions
    for (cname, label, params, ret) in &g.externs {
        let mut cps = vec![];
        let mut args = vec![];
        for (i, k) in params.iter().enumerate() {
            match k.as_str() {
                "str" => {
                    cps.push(format!("p{i}"));
                    cps.push(format!("n{i}"));
                    args.push(format!("str(p{i}, n{i})"));
                }
                k if k.starts_with("ptr:") => {
                    cps.push(format!("p{i}"));
                    cps.push(format!("n{i}"));
                    args.push(format!("new {}(mem.buffer, p{i}, n{i})", typed(&k[4..])));
                }
                "bool" => {
                    cps.push(format!("a{i}"));
                    args.push(format!("a{i} !== 0"));
                }
                _ => {
                    cps.push(format!("a{i}"));
                    args.push(format!("a{i}"));
                }
            }
        }
        let body = match ret.as_str() {
            "void" => format!("call(\"{cname}\", [{}]);", args.join(", ")),
            "bool" => format!("return call(\"{cname}\", [{}]) ? 1 : 0;", args.join(", ")),
            "float" => format!("return +call(\"{cname}\", [{}]) || 0;", args.join(", ")),
            _ => format!("return call(\"{cname}\", [{}]) | 0;", args.join(", ")),
        };
        let _ = writeln!(o, "    // {label}\n    {cname}({}) {{ {body} }},", cps.join(", "));
    }
    o.push_str(
        r#"  };
  let bytes = wasm;
  if (wasm instanceof URL || typeof wasm === "string") {
    const url = wasm instanceof URL ? wasm : new URL(wasm, import.meta.url);
    if (url.protocol === "file:" && typeof process !== "undefined") {
      const { readFile } = await import("node:fs/promises");
      bytes = await readFile(url);
    } else {
      bytes = await (await fetch(url)).arrayBuffer();
    }
  }
  const { instance } = await WebAssembly.instantiate(bytes, { env });
  x = instance.exports;
  mem = x.memory;
  // a panic unwinds as a JS exception: put the stack pointer back and let the C side finish the
  // API call the way its catch point does natively
  const guarded = (f, onPanic) => (...a) => {
    const sp = x.__stack_pointer.value;
    try { return f(...a); } catch (e) {
      if (e !== UNWIND) throw e;
      x.__stack_pointer.value = sp;
      const g = x.P_wasm_unwound();
      return onPanic(g);
    }
  };
  const cstr = (s) => { const b = enc.encode(s + "\0"); const p = x.P_wasm_alloc(b.length); u8().set(b, p); return p; };
  const scratch = x.P_wasm_alloc(8);
  const lenAt = () => new Int32Array(mem.buffer, scratch, 1)[0];
  const create = guarded((seed) => x.P_create(BigInt(seed)), (g) => g);
  const step = guarded((g) => x.P_step(g), () => 0);
  const loadState = guarded((g, p) => x.P_load(g, p), () => 0);
  let g = 0;
  const game = {
    exports: x, memory: mem, files,
    /** makes the world and runs Game.Start (check error()); returns this */
    create(seed = 0n) { if (g) x.P_destroy(g); g = create(seed); if (!g) throw new Error("sijo: out of memory"); return game; },
    /** one tick (1/60 s): 1 ok, 0 stopped by a panic (see error()), -1 bad call */
    step() { return step(g); },
    /** the panic message (with .sijo file:line) of a stopped game, or null */
    error() { const p = x.P_error(g); return p ? cstrAt(p) : null; },
    tick() { return x.P_tick(g); },
    /** layout-independent hash of the world (BigInt): the same as a native build's */
    checksum() { return BigInt.asUintN(64, x.P_checksum(g)); },
    drawCount() { return x.P_draw_count(g); },
    /** draw command i of the last client frame: { sprite, x, y, text } (text: null for a sprite) */
    draw(i) {
      const n = x.P_draw_text_len(g, i);
      return { sprite: x.P_draw_sprite(g, i), x: x.P_draw_x(g, i), y: x.P_draw_y(g, i), text: n > 0 ? str(x.P_draw_text(g, i), n) : null };
    },
    draws() { const n = x.P_draw_count(g), v = new Array(n); for (let i = 0; i < n; i++) v[i] = game.draw(i); return v; },
    /** saves the world under `name` in `files` and returns the bytes (null on failure) */
    save(name = "game.state") { const p = cstr(name); const ok = x.P_save(g, p); x.P_wasm_free(p); return ok ? files.get(name) : null; },
    /** restores a state saved by save() (a name in `files`, or the bytes); also restarts a stopped game */
    load(state = "game.state") {
      const name = typeof state === "string" ? state : "sijo:loaded-bytes";
      if (typeof state !== "string") files.set(name, state);
      const p = cstr(name); const ok = loadState(g, p); x.P_wasm_free(p); return ok === 1;
    },
    destroy() { if (g) x.P_destroy(g); g = 0; },
    fields: {},
  };
"#
        .replace("P_", &format!("{}_", prefix))
        .as_str(),
    );
    // entity field accessors: game.fields.World_G(i) ...
    let short = |n: &str| n.strip_prefix(&format!("{}_", prefix)).unwrap_or(n).to_string();
    for (cname, kind, what) in &g.accessors {
        let key = short(cname);
        let line = match kind.as_str() {
            "count" => format!("  game.fields.{key} = () => x.{cname}(g); // live {what} entities"),
            "id" | "handle" => format!("  game.fields.{key} = (i = 0) => BigInt.asUintN(64, x.{cname}(g, i)); // {what}"),
            "str" => format!("  game.fields.{key} = (i = 0) => {{ const p = x.{cname}(g, i, scratch); return p ? str(p, lenAt()) : null; }}; // {what}"),
            k if k.starts_with("ptr:") => format!(
                "  game.fields.{key} = (i = 0) => {{ const p = x.{cname}(g, i, scratch); return p ? new {}(mem.buffer, p, lenAt()) : null; }}; // {what} (a view: valid until the next step)",
                typed(&k[4..])
            ),
            "bool" => format!("  game.fields.{key} = (i = 0) => x.{cname}(g, i) !== 0; // {what}"),
            _ => format!("  game.fields.{key} = (i = 0) => x.{cname}(g, i); // {what}"),
        };
        o.push_str(&line);
        o.push('\n');
    }
    o.push_str("  return game;\n}\n");
    o
}

/// a page that runs the game at 60 ticks per second and draws its draw list on a canvas
pub fn page(stem: &str) -> String {
    r##"<!doctype html>
<!-- written by sijoc build --target wasm32 (once: edit it freely; sijoc does not overwrite it).
     Serve this directory over HTTP (python3 -m http.server) and open index.html. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>STEM</title>
<style>
  body { margin: 0; background: #101114; color: #d8dae0; font: 14px/1.4 ui-monospace, monospace; }
  canvas { display: block; margin: 16px auto; background: #000; image-rendering: pixelated; max-width: calc(100vw - 32px); }
  #status { text-align: center; }
  #error { color: #ff7b72; white-space: pre-wrap; text-align: center; }
</style>
</head>
<body>
<canvas id="screen" width="960" height="540"></canvas>
<div id="status"></div>
<div id="error"></div>
<script type="module">
import { load } from "./STEM.js";

// world units -> pixels (Draw.Sprite / Draw.Text coordinates)
const SCALE = 8;
const keys = new Set();
addEventListener("keydown", (e) => keys.add(e.key));
addEventListener("keyup", (e) => keys.delete(e.key));

// the game's host functions (extern in Sijo), by C name: strings arrive as JS strings, arrays as
// typed arrays (read them during the call). Example: is_key_down(code) { return keys.has(...); }
const host = {
  print: (fd, line) => (fd === 2 ? console.error : console.log)(line),
};

const game = (await load(host)).create(BigInt(Date.now()));
const screen = document.getElementById("screen");
const ctx = screen.getContext("2d");
const status = document.getElementById("status");
const error = document.getElementById("error");

function draw() {
  ctx.fillStyle = "#000";
  ctx.fillRect(0, 0, screen.width, screen.height);
  ctx.font = "14px monospace";
  for (const d of game.draws()) {
    const px = d.x * SCALE, py = d.y * SCALE;
    if (d.text !== null) {
      ctx.fillStyle = "#d8dae0";
      ctx.fillText(d.text, px, py);
    } else {
      ctx.fillStyle = `hsl(${(d.sprite * 47) % 360} 70% 60%)`;
      ctx.fillRect(px - SCALE / 2, py - SCALE / 2, SCALE, SCALE);
    }
  }
  status.textContent = `tick ${game.tick()}`;
}

// fixed 60 ticks per second, whatever the display's refresh rate
const DT = 1000 / 60;
let last = performance.now(), acc = 0;
function frame(now) {
  acc += Math.min(now - last, 250);
  last = now;
  while (acc >= DT) {
    acc -= DT;
    if (game.step() !== 1) {
      error.textContent = game.error() ?? "the game stopped";
      draw();
      return;
    }
  }
  draw();
  requestAnimationFrame(frame);
}
if (game.error()) error.textContent = game.error(); else requestAnimationFrame(frame);
</script>
</body>
</html>
"##
    .replace("STEM", stem)
}
